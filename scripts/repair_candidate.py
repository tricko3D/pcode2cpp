#!/usr/bin/env python3
"""Try one local model repair of an existing compiler-failing C++ candidate.

Only the fixed function prefix, the previous body, and concise diagnostics go
back to Inkling. No Ghidra context is regenerated; no model tools are exposed.
The original candidate is never edited, and there is no automatic retry loop.
"""

import argparse
import json
from pathlib import Path
import re
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

if __package__:
    from .check_candidate import check_candidate
    from .probe_body import PREFIX, ROOT, SCHEMA
else:
    from check_candidate import check_candidate
    from probe_body import PREFIX, ROOT, SCHEMA


def extract_body(source: str) -> str:
    """Reject unexpected prefixes instead of asking Inkling to fix the harness."""
    if not source.startswith(PREFIX) or not source.rstrip().endswith("}"):
        raise ValueError("Candidate does not use the probe's fixed function prefix")
    body = source[len(PREFIX):].rstrip()
    body = body[:-1].strip("\n")  # remove final function-closing brace
    if not body.strip():
        raise ValueError("Candidate has an empty function body")
    return body


def concise_errors(diagnostics: str, limit: int = 5) -> list[str]:
    """Only compiler error locations/messages, never the whole verbose log."""
    results = []
    for line in diagnostics.splitlines():
        if "error:" not in line:
            continue
        message = line.strip()
        # Drop machine-specific absolute paths, preserve the source line.
        message = re.sub(r"^.*?\.cpp:(\d+):(\d+): error:", r"line \1:\2: error:", message)
        if message not in results:
            results.append(message)
        if len(results) == limit:
            break
    return results


def make_messages(body: str, errors: list[str]) -> list[dict[str, str]]:
    if not errors:
        raise ValueError("Compiler errors are required for a repair turn")
    return [
        {"role": "system", "content": (
            "You repair compilation errors in 32-bit x86 C++ with the MSVC ABI. "
            "Only repair type or syntax problems; preserve memory accesses, pointer "
            "values, operation order, function calls, and behavior. Integer fields "
            "may intentionally contain 32-bit pointer addresses. In that case, "
            "use explicit 32-bit pointer/integer casts, not dereferences. "
            "Return JSON with one string field 'body' containing only the "
            "corrected C++ statements. No signature, enclosing braces, or prose."
        )},
        {"role": "user", "content": (
            "This fixed prefix is supplied by the harness and cannot change:\n\n"
            + PREFIX + "    // body generated by the model\n}\n\n"
            "Repair the body below without changing its intended semantics."
        )},
        {"role": "assistant", "content": json.dumps({"body": body})},
        {"role": "user", "content": (
            "The 32-bit Clang compile check failed. Its diagnostics are:\n"
            + "\n".join(f"- {error}" for error in errors)
            + "\n\nFix only these errors. Compiler suggestions to dereference or "
              "take an address may change the function's behavior. "
              "Return the complete corrected JSON body."
        )},
    ]


def next_output_path(candidate: Path) -> Path:
    for index in range(1, 10000):
        name = f"{candidate.stem}_repair{index:03d}.cpp"
        path = candidate.with_name(name)
        if not path.exists() and not path.with_suffix(".log").exists():
            return path
    raise RuntimeError("No available repair output path")


def run(candidate: Path, max_tokens: int | None = None) -> int:
    candidate = candidate.resolve()
    source = candidate.read_text(encoding="utf-8")
    body = extract_body(source)
    compile_result = check_candidate(candidate)
    print(f"Existing candidate: {candidate}", flush=True)
    print(f"Initial compiler check: {compile_result.status}", flush=True)
    if compile_result.passed:
        print("Already compiles; no model request needed.", flush=True)
        return 0
    if compile_result.status != "FAIL":
        print(f"Compiler unavailable or timed out: {compile_result.diagnostics}", flush=True)
        return 1
    errors = concise_errors(compile_result.diagnostics)
    if not errors:
        print("No actionable compiler errors; no model request made.", flush=True)
        return 1

    config = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))["llm"]
    payload = {
        "model": config.get("model", "local"),
        "messages": make_messages(body, errors),
        "temperature": config.get("temperature", 0),
        "max_tokens": max_tokens if max_tokens is not None else config.get("max_tokens", 32768),
        "stream": True,
        "response_format": {"type": "json_schema", "schema": SCHEMA},
    }
    output_path = next_output_path(candidate)
    log_path = output_path.with_suffix(".log")
    print(f"Sending one type-repair turn with {len(errors)} compiler errors; no original Ghidra prompt.", flush=True)
    print(f"Output tokens: {payload['max_tokens']}", flush=True)

    req = Request(
        config.get("url", "http://127.0.0.1:8080/v1/chat/completions"),
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
    )
    parts = []
    state = None
    finish_reason = None
    try:
        with urlopen(req, timeout=config.get("timeout_seconds", 1800)) as response:
            with log_path.open("x", encoding="utf-8") as log:
                for raw in response:
                    line = raw.decode("utf-8", errors="replace").strip()
                    if not line.startswith("data:"):
                        continue
                    data = line[5:].strip()
                    if data == "[DONE]":
                        break
                    event = json.loads(data)
                    if "error" in event:
                        raise RuntimeError(str(event["error"]))
                    for choice in event.get("choices", []):
                        delta = choice.get("delta") or {}
                        for section, part in (
                            ("Reasoning", delta.get("reasoning_content") or delta.get("reasoning") or ""),
                            ("JSON", delta.get("content") or ""),
                        ):
                            if not part:
                                continue
                            if state != section:
                                state = section
                                print(f"\n[{section}]\n", flush=True)
                                log.write(f"\n[{section}]\n")
                            print(part, end="", flush=True)
                            log.write(part)
                            log.flush()
                            if section == "JSON":
                                parts.append(part)
                        finish_reason = choice.get("finish_reason") or finish_reason
    except HTTPError as exc:
        print(f"llama.cpp HTTP {exc.code}: {exc.read().decode('utf-8', errors='replace')}")
        return 1
    except (OSError, URLError) as exc:
        print(f"Model connection failed: {exc}")
        return 1
    print(f"\n\nFinish reason: {finish_reason}; transcript: {log_path}", flush=True)
    if finish_reason == "length" or not parts:
        print("Model output is truncated or missing; no repaired candidate saved.", flush=True)
        return 1
    try:
        repaired_body = json.loads("".join(parts))["body"]
        if not isinstance(repaired_body, str) or not repaired_body.strip():
            raise ValueError("body must be a nonempty string")
    except (ValueError, TypeError, KeyError) as exc:
        print(f"Invalid JSON response: {exc}", flush=True)
        return 1

    with output_path.open("x", encoding="utf-8") as handle:
        handle.write(PREFIX + repaired_body.strip("\n") + "\n}\n")
    result = check_candidate(output_path)
    print(f"Repair candidate: {output_path}", flush=True)
    print(f"Compiler check: {result.status}; diagnostics: {result.diagnostics_path}", flush=True)
    if not result.passed:
        print(result.diagnostics, flush=True)
    return 0 if result.passed else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("candidate", type=Path, help="Existing .cpp candidate to repair once")
    parser.add_argument("--max-tokens", type=int, help="Override the local model max_tokens for this repair")
    args = parser.parse_args()
    if args.max_tokens is not None and args.max_tokens < 1:
        parser.error("--max-tokens must be positive")
    try:
        return run(args.candidate, args.max_tokens)
    except (FileNotFoundError, ValueError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    raise SystemExit(main())
